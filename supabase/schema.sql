create or replace function public.create_order(
  p_customer jsonb,
  p_items jsonb,
  p_shipping_cop integer,
  p_payment_provider text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id uuid := gen_random_uuid();
  v_reference text := 'NAYA-' || replace(v_order_id::text, '-', '');
  v_subtotal integer := 0;
  v_total integer;
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
  v_name text;
  v_email text;
  v_phone text;
  v_identification text;
  v_company text;
  v_country text;
  v_address text;
  v_apartment text;
  v_city text;
  v_region text;
  v_postal_code text;
  v_notes text;
begin
  if p_payment_provider not in ('wompi', 'whatsapp') then
    raise exception 'Invalid payment provider';
  end if;

  if p_shipping_cop not in (25000, 30000) then
    raise exception 'Invalid shipping amount';
  end if;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 20 then
    raise exception 'Invalid order items';
  end if;

  v_name := nullif(btrim(concat_ws(' ', nullif(btrim(p_customer->>'nombre'), ''), nullif(btrim(p_customer->>'apellidos'), ''))), '');
  v_email := nullif(btrim(p_customer->>'email'), '');
  v_phone := nullif(btrim(p_customer->>'telefono'), '');
  v_identification := nullif(btrim(p_customer->>'identificacion'), '');
  v_company := nullif(btrim(p_customer->>'empresa'), '');
  v_country := coalesce(nullif(btrim(p_customer->>'pais'), ''), 'Colombia');
  v_address := nullif(btrim(p_customer->>'direccion'), '');
  v_apartment := nullif(btrim(p_customer->>'apartamento'), '');
  v_city := nullif(btrim(p_customer->>'poblacion'), '');
  v_region := nullif(btrim(p_customer->>'departamento'), '');
  v_postal_code := nullif(btrim(p_customer->>'codigoPostal'), '');
  v_notes := nullif(btrim(p_customer->>'notas'), '');

  if v_name is null or v_email is null or v_phone is null or v_identification is null
    or v_address is null or v_city is null or v_region is null then
    raise exception 'Required customer data is missing';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce(v_item->>'id', '') !~ '^[0-9]+$' or coalesce(v_item->>'cantidad', '') !~ '^[0-9]+$' then
      raise exception 'Invalid product or quantity';
    end if;

    v_quantity := (v_item->>'cantidad')::integer;
    if v_quantity < 1 or v_quantity > 99 then
      raise exception 'Invalid product quantity';
    end if;

    select * into v_product
    from public.products
    where id = (v_item->>'id')::bigint and active = true;

    if not found then
      raise exception 'Product is unavailable';
    end if;

    v_subtotal := v_subtotal + v_product.price_cop * v_quantity;
  end loop;

  v_total := v_subtotal + p_shipping_cop;

  insert into public.orders (
    id, reference, customer_name, customer_email, customer_phone,
    customer_identification, customer_company, shipping_country,
    shipping_address, shipping_apartment, shipping_city, shipping_region,
    shipping_postal_code, customer_notes, subtotal_cop,
    shipping_cop, total_cop, payment_provider
  ) values (
    v_order_id, v_reference, v_name, v_email, v_phone,
    v_identification, v_company, v_country, v_address, v_apartment,
    v_city, v_region, v_postal_code, v_notes, v_subtotal,
    p_shipping_cop, v_total, p_payment_provider
  );

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := (v_item->>'cantidad')::integer;
    select * into v_product
    from public.products
    where id = (v_item->>'id')::bigint and active = true;

    insert into public.order_items (
      order_id, product_id, product_name, unit_price_cop, quantity, line_total_cop
    ) values (
      v_order_id, v_product.id, v_product.name, v_product.price_cop,
      v_quantity, v_product.price_cop * v_quantity
    );
  end loop;

  return jsonb_build_object(
    'id', v_order_id,
    'reference', v_reference,
    'subtotal', v_subtotal,
    'shippingCost', p_shipping_cop,
    'total', v_total
  );
end;
$$;

create or replace function public.get_order_payment_data(p_order_id uuid)
returns table (reference text, amount_in_cents bigint)
language sql
stable
security definer
set search_path = ''
as $$
  select o.reference, o.total_cop::bigint * 100
  from public.orders o
  where o.id = p_order_id and o.payment_status = 'pending';
$$;

create or replace function public.get_order_payment_status(p_reference text)
returns table (payment_status text, order_status text)
language sql
stable
security definer
set search_path = ''
as $$
  select o.payment_status, o.order_status
  from public.orders o
  where o.reference = p_reference;
$$;

revoke all on function public.create_order(jsonb, jsonb, integer, text) from public;
revoke all on function public.get_order_payment_data(uuid) from public;
revoke all on function public.get_order_payment_status(text) from public;
grant execute on function public.create_order(jsonb, jsonb, integer, text) to anon, authenticated;
grant execute on function public.get_order_payment_data(uuid) to anon, authenticated;
grant execute on function public.get_order_payment_status(text) to anon, authenticated;

