create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null,
  name text not null,
  description text not null,
  details text,
  price_cop integer not null check (price_cop >= 0),
  image_url text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'products'
      and column_name = 'id'
      and is_identity = 'YES'
  ) then
    alter table public.products alter column id add generated by default as identity;
  end if;
end;
$$;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  customer_identification text not null,
  customer_company text,
  shipping_country text not null default 'Colombia',
  shipping_address text not null,
  shipping_apartment text,
  shipping_city text not null,
  shipping_region text not null,
  shipping_postal_code text,
  customer_notes text,
  subtotal_cop integer not null check (subtotal_cop >= 0),
  shipping_cop integer not null check (shipping_cop in (25000, 30000)),
  total_cop integer not null check (total_cop = subtotal_cop + shipping_cop),
  order_status text not null default 'pending' check (order_status in ('pending', 'processing', 'shipped', 'completed', 'cancelled')),
  payment_status text not null default 'pending' check (payment_status in ('pending', 'approved', 'declined', 'voided', 'error')),
  payment_provider text not null default 'wompi' check (payment_provider in ('wompi', 'whatsapp')),
  payment_transaction_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price_cop integer not null check (unit_price_cop >= 0),
  quantity integer not null check (quantity between 1 and 99),
  line_total_cop integer not null check (line_total_cop = unit_price_cop * quantity),
  created_at timestamptz not null default now()
);

create table if not exists public.email_notifications (
  event_key text primary key,
  created_at timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_payment_status_idx on public.orders (payment_status);
create index if not exists order_items_order_id_idx on public.order_items (order_id);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.admin_users enable row level security;
alter table public.email_notifications enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid()) and enabled = true
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

drop policy if exists "Anyone can read active products" on public.products;
create policy "Anyone can read active products"
  on public.products for select
  using (active = true);

drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products"
  on public.products for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Admins read orders" on public.orders;
create policy "Admins read orders"
  on public.orders for select to authenticated
  using (public.is_admin());

drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders"
  on public.orders for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Admins read order items" on public.order_items;
create policy "Admins read order items"
  on public.order_items for select to authenticated
  using (public.is_admin());

drop policy if exists "Users read own admin membership" on public.admin_users;
create policy "Users read own admin membership"
  on public.admin_users for select to authenticated
  using (user_id = (select auth.uid()));

grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;
grant select on public.orders to authenticated;
revoke update on public.orders from authenticated;
grant update (order_status, updated_at) on public.orders to authenticated;
grant select on public.order_items to authenticated;
grant select on public.admin_users to authenticated;

revoke all on public.orders from anon, authenticated;
revoke all on public.order_items from anon, authenticated;
revoke all on public.email_notifications from anon, authenticated;
